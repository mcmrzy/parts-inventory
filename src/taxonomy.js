// 落库时的噪声键（无筛选价值，归一化时丢弃）
export const KEY_NOISE = /工作结温范围|结温范围|工作温度|存储温度|工作寿命|检测温度|温度转换时间|数量$/;

/** 类目的标准字段定义（无匹配用默认） */
export function facetDefs(category) {
  return DEFS[String(category || '').trim()] || DEFS['默认'];
}

/** 值清理：占位横杠丢弃（保留纯数字，如 PIN 数=6 是有效值） */
function cleanStored(v) {
  const s = String(v).trim();
  return (!s || /^[-–—]+$/.test(s)) ? null : s;
}

/**
 * 把立创原始参数归一到标准字段：
 * - 命中别名的键改名为标准键（标准键优先，后写不覆盖）
 * - 未命中的键按原名保留在后面；噪声键丢弃
 * - 半导体类目：若缺"器件类型"，从名称/型号关键词推导（肖特基/稳压/ESD…）
 */
export function canonicalizeAttributes(category, attrs, name) {
  const out = {};
  const src = (attrs && typeof attrs === 'object') ? attrs : {};
  const defs = facetDefs(category);
  const used = new Set();
  for (const [ckey, aliases] of defs) {
    for (const a of aliases) {
      if (src[a] !== undefined) {
        const v = cleanStored(src[a]);
        if (v != null) { out[ckey] = v; used.add(a); }
        break;
      }
    }
  }
  for (const [k, v] of Object.entries(src)) {
    if (used.has(k) || KEY_NOISE.test(k)) continue;
    const cv = cleanStored(v);
    if (cv != null && out[k] === undefined) out[k] = cv;
  }
  // 半导体类目：从名称推导器件类型
  if (/二极管|MOSFET|晶体管|三极管|分立器件/.test(String(category || '')) && !out['器件类型']) {
    const hay = `${name || ''} ${src['型号'] || ''}`;
    for (const w of SEMI_NAME_WORDS) {
      if (hay.toUpperCase().includes(w.toUpperCase())) { out['器件类型'] = w; break; }
    }
  }
  return Object.keys(out).length ? out : null;
}
